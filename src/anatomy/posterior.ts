const vertebraHalfWidth = (id: string): number =>
  id.startsWith("C") ? 15 : id.startsWith("T") ? 21 : 29;

const vertebraeShapes = (): Shape[] =>
  SPINE.filter((v) => !v.id.startsWith("S")).map((v) => {
    const hw = vertebraHalfWidth(v.id);
    const h = v.id.startsWith("C") ? 4.5 : v.id.startsWith("T") ? 6.5 : 8.5;
    const outline: Pt[] = [
      [300 - hw, v.y - h],
      [300 - hw * 0.45, v.y - h * 1.5],
      [300 + hw * 0.45, v.y - h * 1.5],
      [300 + hw, v.y - h],
      [300 + hw * 0.7, v.y + h],
      [300 + hw * 0.22, v.y + h * 1.35],
      [300 - hw * 0.22, v.y + h * 1.35],
      [300 - hw * 0.7, v.y + h],
    ];
    return {
      id: `vertebra-${v.id.toLowerCase()}`,
      label: `${v.id} vertebra`,
      layer: 3,
      tissue: "bone",
      outline,
      fibres: { kind: "none" },
      z: 6,
      priority: 3,
      hitPad: 2,
    } satisfies Shape;
  });

/**
 * Twelve rib pairs. Reach is capped to the width of the trunk at that height —
 * ribs curve forward around the chest, so in a posterior view they only ever
 * read as far as the body's own outline.
 */
const ribShapes = (): Shape[] => {
  const out: Shape[] = [];
  for (let i = 1; i <= 12; i++) {
    const top = spineY(`T${i}`);
    const t = (i - 1) / 11;
    const reach = 56 + 46 * Math.sin(t * Math.PI * 0.82);
    const drop = 22 + 44 * t;
    const centre: Pt[] = [
      [278, top + 2],
      [278 - reach * 0.44, top + drop * 0.4],
      [278 - reach * 0.8, top + drop * 0.88],
      [278 - reach, top + drop * 1.45],
    ];
    out.push({
      id: `rib-${i}`,
      label: `Rib ${i}`,
      layer: 3,
      tissue: "bone",
      outline: ribbon(centre, 7),
      bilateral: true,
      fibres: { kind: "none" },
      z: 4,
      priority: 1,
      hitPad: 3,
    });
  }
  return out;
};

