/** Videos for a structure, best-matching purpose first. */
export function mediaFor(
  structureId: string,
  purpose?: CuratedMedia["purpose"],
): CuratedMedia[] {
  const hits = MEDIA.filter((m) => m.targets.includes(structureId));
  if (!purpose) return hits;
  return [
    ...hits.filter((m) => m.purpose === purpose),
    ...hits.filter((m) => m.purpose !== purpose),
  ];
}
